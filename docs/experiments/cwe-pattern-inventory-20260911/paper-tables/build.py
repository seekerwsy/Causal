"""Render descriptive source-inventory tables; no model calls or study assignment.

Run from any directory with Python 3.12+. Counts are checked against the exact
candidate-pool snapshot recorded in the existing inventory before rendering.
"""

import csv
import hashlib
import json
from pathlib import Path


HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[3]
INVENTORY = HERE.parent / "inventory.json"
POOL = ROOT / "data/dataset-curation/research-candidate-pool-v2/tasks.json"
GROUPS = [
    ("Memory and resources", [119,120,121,125,131,134,170,190,193,242,252,369,400,406,414,416,468,476,590,665,676,680,703,770,787,835,908]),
    ("Injection and interpretation", [74,77,78,79,80,89,90,91,94,95,99,113,116,117,643,943,1236]),
    ("Crypto and randomness", [208,295,321,323,326,327,328,329,330,331,335,338,339,347,385,759,760,1204,1240]),
    ("Identity, credentials, and trust", [200,209,215,250,259,269,283,285,290,306,312,319,345,348,352,425,454,521,522,554,614,798,807,841,862,863,915]),
    ("Input processing", [20,176,179,185,502,611,776,827,1333]),
    ("Files and networks", [22,276,281,367,377,379,434,601,605,641,732,918,941]),
    ("API and logic correctness", [462,477,589,595]),
    ("Historical category", [730]),
]


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def tex(value):
    escapes = {"&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#",
               "_": r"\_", "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}",
               "^": r"\textasciicircum{}", "\\": r"\textbackslash{}"}
    return "".join(escapes.get(c, c) for c in str(value))


def write(name, text):
    (HERE / name).write_text(text, encoding="utf-8", newline="\n")


inventory = json.loads(INVENTORY.read_text(encoding="utf-8"))
assert sha(POOL) == inventory["input_sha256"][POOL.relative_to(ROOT).as_posix()]
with (HERE / "display.tsv").open(encoding="utf-8", newline="") as handle:
    display_rows = list(csv.DictReader(handle, delimiter="\t"))
display = {r["cwe"]: r for r in display_rows}
rows = {r["cwe"]: r for r in inventory["cwe_rows"]}
assert len(display_rows) == len(display) == len(rows) == 117
assert display.keys() == rows.keys()
grouped_ids = [f"CWE-{i}" for _, ids in GROUPS for i in ids]
assert len(grouped_ids) == len(set(grouped_ids)) == 117
assert set(grouped_ids) == set(rows)

# Use only source labels and task identities here, never outcomes or task text.
pool_metadata = [(r["task_unit_id"], r["near_duplicate_group_id"], r["source_declared_cwe_ids"])
                 for r in json.loads(POOL.read_text(encoding="utf-8"))]
assert len(pool_metadata) == len({r[0] for r in pool_metadata}) == len({r[1] for r in pool_metadata}) == 1992
members = {cwe: {task_id for task_id, _, labels in pool_metadata if cwe in labels} for cwe in rows}
assert all(len(members[cwe]) == r["pool_task_units"] for cwe, r in rows.items())
selected = sorted(rows, key=lambda cwe: (-len(members[cwe]), int(cwe.split("-")[1])))[:20]
selected_units = set().union(*(members[cwe] for cwe in selected))
all_units = set().union(*members.values())
coverage = 100 * len(selected_units) / len(all_units)
assert len(all_units) == 1992
assert sum(map(len, members.values())) == 1993


def row(cwe, category=""):
    d = display[cwe]
    label = tex(cwe) + ": " + tex(d["description"])
    return " & ".join([category, label, tex(d["illustrative_forms"]), f"{len(members[cwe]):,}"]) + r" \\" + "\n"


header = r"\textbf{Category} & \textbf{CWE (ID \& description)} & \textbf{Illustrative task forms} & \textbf{Tasks} \\" + "\n"
notes = (
    r"\textit{Notes.} Counts refer to deduplicated task units carrying each source label, "
    r"not to individual patterns, validated vulnerabilities, or eligible interventions. "
    r"The task forms summarize inspected examples; they are not an exhaustive pattern taxonomy. "
    r"Categories are editorial groupings and CWE descriptions are abbreviated. "
    r"One task carries both CWE-120 and CWE-121; totals count that task once."
)

main = [
    "% Generated by build.py from inventory.json and display.tsv. Descriptive data only.\n",
    r"\begin{table}[tp]" + "\n" + r"\centering" + "\n",
    r"\caption{The 20 most frequent source CWE labels in the candidate pool. "
    + f"Together they cover {len(selected_units):,} of {len(all_units):,} independent task units ({coverage:.1f}"
    + r"\%).}" + "\n",
    r"\label{tab:cwe-task-forms-main}" + "\n",
    r"\begingroup\small\setlength{\tabcolsep}{3pt}\renewcommand{\arraystretch}{1.08}" + "\n",
    r"\begin{tabularx}{\linewidth}{@{}>{\raggedright\arraybackslash}p{.13\linewidth} >{\raggedright\arraybackslash}p{.25\linewidth} >{\raggedright\arraybackslash}X r@{}}" + "\n",
    r"\toprule" + "\n", header, r"\midrule" + "\n",
]
used_groups = []
for group, ids in GROUPS:
    ids = [f"CWE-{i}" for i in ids if f"CWE-{i}" in selected]
    if not ids:
        continue
    ids.sort(key=lambda cwe: (-len(members[cwe]), int(cwe.split("-")[1])))
    if used_groups:
        main.append(r"\midrule" + "\n")
    for i, cwe in enumerate(ids):
        category = (r"\multirow[t]{" + str(len(ids)) + r"}{=}{\raggedright\textbf{" + tex(group) + "}}") if i == 0 else ""
        main.append(row(cwe, category))
    used_groups.append({"category": group, "cwe_ids": ids,
                        "unique_task_units": len(set().union(*(members[cwe] for cwe in ids)))})
main.extend([
    r"\midrule" + "\n",
    r"\multicolumn{3}{@{}l}{\textbf{Selected total (unique task units)}} & \textbf{" + f"{len(selected_units):,}" + r"} \\" + "\n",
    r"\bottomrule" + "\n" + r"\end{tabularx}" + "\n",
    r"\par\smallskip\begin{minipage}{\linewidth}\footnotesize " + notes + r"\end{minipage}" + "\n",
    r"\endgroup" + "\n" + r"\end{table}" + "\n",
])
write("cwe-main.tex", "".join(main))

# Longtable repeats the column header and may break between rows. Category names
# repeat within the first column so a page break never loses a row's grouping.
appendix = [
    "% Requires booktabs, longtable, and array. Generated by build.py.\n",
    r"\begingroup\small\setlength{\tabcolsep}{3pt}\renewcommand{\arraystretch}{1.14}" + "\n",
    r"\begin{longtable}{@{}>{\raggedright\arraybackslash}p{.13\linewidth} >{\raggedright\arraybackslash}p{.25\linewidth} >{\raggedright\arraybackslash}p{\dimexpr.62\linewidth-43pt\relax} r@{}}" + "\n",
    r"\caption{Complete source-CWE inventory: 117 labels across 1,992 independent task units. "
    r"There are 116 weakness entries and one historical category (CWE-730).}" + "\n",
    r"\label{tab:cwe-task-forms-appendix}\\" + "\n",
    r"\toprule" + "\n", header, r"\midrule" + "\n" + r"\endfirsthead" + "\n",
    r"\multicolumn{4}{@{}l}{\textit{Table \thetable\ continued}}\\" + "\n",
    r"\toprule" + "\n", header, r"\midrule" + "\n" + r"\endhead" + "\n",
    r"\midrule\multicolumn{4}{r@{}}{\footnotesize Continued on next page}\\" + "\n" + r"\endfoot" + "\n",
    r"\bottomrule" + "\n" + r"\endlastfoot" + "\n",
]
appendix_category_names = ["Memory / resources", "Injection", "Crypto / randomness",
                          "Identity / trust", "Input", "Files / networks", "API / logic", "Historical"]
for j, (group, ids) in enumerate(GROUPS):
    if j:
        appendix.append(r"\midrule" + "\n")
    for number in ids:
        appendix.append(row(f"CWE-{number}", tex(appendix_category_names[j])))
appendix.extend([
    r"\midrule\multicolumn{3}{@{}l}{\textbf{Total (unique task units)}} & \textbf{1,992} \\" + "\n",
    r"\end{longtable}" + "\n",
    r"\noindent\begin{minipage}{\linewidth}\footnotesize " + notes
    + r" The underlying inventory contains 214 inspected source examples, not 214 distinct patterns. "
    r"Full source descriptions and example task identities are retained in the inventory workbook."
    + r"\end{minipage}" + "\n" + r"\endgroup" + "\n",
])
write("cwe-appendix.tex", "".join(appendix))

profile = r"""\documentclass[acmsmall,screen,review,anonymous]{acmart}
\settopmatter{printacmref=false}
\setcopyright{none}
\usepackage{booktabs,multirow,tabularx,longtable}
\begin{document}
\pagestyle{plain}
\typeout{TABLE-PROFILE: linewidth=\the\linewidth; textheight=\the\textheight}
"""
write("preview.tex", profile + r"""\input{cwe-main.tex}
\clearpage
\input{cwe-appendix.tex}
\end{document}
""")
write("main-preview.tex", profile + r"""\input{cwe-main.tex}
\end{document}
""")

report = {
    "status": "DESCRIPTIVE_TABLES_GENERATED_NOT_SCIENTIFIC_EFFECT_RESULTS",
    "selection_rule": "20 most frequent source CWE labels in the 1,992-task candidate pool; descending count, ascending numeric CWE ID for ties",
    "selection_changes_study_scope": False,
    "selected_cwe_ids_by_rank": selected,
    "main_cwe_rows": len(selected),
    "main_cwe_memberships": sum(len(members[cwe]) for cwe in selected),
    "main_unique_task_units": len(selected_units),
    "main_candidate_pool_coverage_percent": coverage,
    "main_categories": used_groups,
    "appendix_cwe_rows": len(rows),
    "appendix_cwe_memberships": sum(map(len, members.values())),
    "appendix_unique_task_units": len(all_units),
    "source_example_count": inventory["source_example_count"],
    "pattern_count": None,
    "per_pattern_counts": None,
    "generated_code_or_outcomes_used": False,
    "provider_calls": 0,
    "formal_use_authorized": False,
    "input_sha256": {str(p.relative_to(ROOT).as_posix()): sha(p) for p in [INVENTORY, POOL, HERE / "display.tsv", Path(__file__)]},
    "output_sha256": {name: sha(HERE / name) for name in ["cwe-main.tex", "cwe-appendix.tex", "preview.tex", "main-preview.tex"]},
}
write("table-data.json", json.dumps(report, indent=2, ensure_ascii=False) + "\n")
print(json.dumps({k: report[k] for k in ["main_cwe_rows", "main_unique_task_units", "main_candidate_pool_coverage_percent", "appendix_cwe_rows", "appendix_unique_task_units"]}, indent=2))
